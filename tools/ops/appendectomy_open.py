def s_close():
    layers = LAYERS_RIF
    s, ys = wall(60, 60, 330, layers)
    def at(i): return (ys[i][1] + ys[i][2]) / 2
    s += suture(f'M110 {at(6)} ' + ' '.join(f'Q{x + 10} {at(6) - 9} {x + 20} {at(6)}' for x in range(110, 340, 20)))
    for i in (3, 4):
        for x in (150, 230, 310):
            s += suture(f'M{x - 12} {at(i)} q12 -14 24 0', 2) + knot(x, at(i) - 7, 3)
    for x in (130, 200, 270, 340):
        s += suture(f'M{x - 10} {at(2)} q10 -10 20 0', 2) + knot(x, at(2) - 5, 3)
        s += suture(f'M{x - 10} {ys[1][1] + 4} Q{x} {ys[0][1] - 10} {x + 10} {ys[1][1] + 4}', 2) + knot(x, ys[0][1] - 4, 3)
    s += text(30, 380, 'Брюшина — непрерывный шов; мышцы — 2–3 узловых; апоневроз и кожа — узловые швы', sm=True)
    return svg(s, 'Послойное ушивание раны')


