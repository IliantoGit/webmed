def tube(x1=70, x2=470, y=220):
    return (path(f'M{x1} {y} L{x2} {y}', stroke='#b7791f', sw=18, extra='stroke-linecap="round"')
            + path(f'M{x1} {y} L{x2} {y}', stroke=C['tube'], sw=14, extra='stroke-linecap="round"'))


