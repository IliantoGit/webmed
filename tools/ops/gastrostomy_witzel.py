def s_fix():
    s = rect(40, 50, 560, 330, C['skin'], stroke=C['skin_line'], sw=2, rx=20)
    s += path('M220 80 L220 340', stroke=C['skin_line'], sw=3)
    for y in range(95, 340, 30):
        s += suture(f'M208 {y} L232 {y}', 2.4) + knot(220, y, 2.5)
    s += circle(430, 220, 26, '#e7b9a8', stroke=C['skin_line'], sw=2) + circle(430, 220, 12, C['tube'], stroke='#b7791f', sw=3)
    s += suture('M404 220 Q395 200 418 210', 2) + suture('M456 220 Q465 240 442 230', 2)
    s += path('M430 220 Q520 160 590 120', stroke='#b7791f', sw=14) + path('M430 220 Q520 160 590 120', stroke=C['tube'], sw=10)
    s += place(t_clamp(), 560, 140, -30, 0.5)
    s += label(220, 200, 'лапаротомная рана\nзашита наглухо', 60, 380, anchor='start')
    s += label(418, 210, 'трубка фиксирована\nнитями-держалками к коже', 300, 80, anchor='start', sm=True)
    s += label(560, 140, 'зажим на трубке', 470, 330, anchor='start', sm=True)
    return svg(s, 'Фиксация трубки, закрытие раны')


