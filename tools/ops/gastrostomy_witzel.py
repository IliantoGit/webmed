def wall_panel(note=True):
    """Передняя стенка желудка крупным планом: сверху малая кривизна, снизу большая."""
    s = path('M40 110 Q320 70 600 110 L600 330 Q320 380 40 330 Z', fill=C['stomach'], stroke=C['stomach_line'], sw=2)
    s += path('M40 110 Q320 70 600 110', stroke=C['stomach_line'], sw=5)
    s += path('M40 330 Q320 380 600 330', stroke=C['stomach_line'], sw=5)
    for x in range(80, 600, 70):
        s += path(f'M{x} {98 - (x - 320) ** 2 / 9000 + 12} q-4 6 0 12', stroke=C['artery'], sw=1.4)
    if note:
        s += text(50, 100, 'малая кривизна', sm=True)
        s += text(50, 368, 'большая кривизна', sm=True)
        s += text(600, 66, 'к дну →', anchor='end', sm=True, color=C['muted'])
        s += text(40, 66, '← к привратнику', sm=True, color=C['muted'])
    return s


