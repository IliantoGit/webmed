def stump(nerve_cut=False, ligated=False):
    cy = 210
    s = ''
    for sgn in (-1, 1):
        s += path(f'M40 {cy + sgn * 168} L330 {cy + sgn * 168} Q420 {cy + sgn * 120} 420 {cy + sgn * 20}', stroke=C['skin_line'], sw=18)
        s += path(f'M40 {cy + sgn * 168} L330 {cy + sgn * 168} Q420 {cy + sgn * 120} 420 {cy + sgn * 20}', stroke=C['skin'], sw=16)
        s += path(f'M40 {cy + sgn * 132} L320 {cy + sgn * 132} Q390 {cy + sgn * 100} 395 {cy + sgn * 30} L330 {cy + sgn * 30} L330 {cy + sgn * 128} Z', fill='url(#fib)')
        s += path(f'M40 {cy + sgn * 90} L330 {cy + sgn * 90} L330 {cy + sgn * 30} L40 {cy + sgn * 30} Z', fill='url(#fibh)')
    s += rect(40, cy - 28, 250, 56, C['bone'], stroke=C['bone_line'], sw=2) + rect(40, cy - 12, 250, 24, C['marrow'])
    s += path(f'M40 {cy + 50} L330 {cy + 50}', stroke=C['artery'], sw=5)
    s += path(f'M40 {cy + 62} L330 {cy + 62}', stroke=C['vein'], sw=6)
    nx = 270 if nerve_cut else 330
    s += path(f'M40 {cy - 55} L{nx} {cy - 55}', stroke=C['nerve'], sw=6)
    if ligated:
        s += ligature(300, cy + 40, 304, cy + 60) + ligature(318, cy + 40, 322, cy + 60) + ligature(310, cy + 54, 314, cy + 72)
    return s


def s_vessels():
    s = stump(ligated=True)
    s += label(320, 250, 'бедренная артерия — две лигатуры,\nдистальная — прошивная', 360, 330, anchor='start')
    s += label(312, 272, 'вена — отдельно', 360, 385, anchor='start', sm=True)
    s += text(360, 60, 'всё крупное перевязывают ДО снятия жгута;\nконцы лигатур срезают после его снятия;\nпрободающие ветви — с прошиванием тканей', sm=True)
    return svg(s, 'Перевязка сосудов культи')


def s_nerves():
    s = stump(nerve_cut=True, ligated=True)
    s += place(t_scalpel(), 272, 155, 70, 0.6)
    s += arrow(330, 120, 280, 120)
    s += label(270, 155, 'седалищный нерв: ткани\nотодвинуть на 5–6 см,\nпересечь лезвием бритвы\nили острым скальпелем', 360, 40, anchor='start')
    s += text(40, 385, 'НЕ вытягивать; НЕ резать ножницами — неврома должна уйти из рубца', sm=True, color=C['cut'])
    return svg(s, 'Усечение нервов')


def s_close():
    cy = 210
    s = stump(nerve_cut=True, ligated=True)
    s += path(f'M420 {cy - 20} L420 {cy + 20}', stroke=C['skin_line'], sw=18)
    for y in range(cy - 16, cy + 20, 12):
        s += suture(f'M410 {y} L430 {y}', 2.2) + knot(420, y, 2)
    s += path('M400 230 Q470 260 560 250', stroke=C['tube'], sw=8)
    s += label(420, 200, 'фасция и кожа ушиты над\nконусом; рубец на торце', 450, 100, anchor='start')
    s += label(520, 252, 'дренаж', 520, 330, anchor='start', sm=True)
    s += label(290, 210, 'опил скрыт в глубине\nмягких тканей', 40, 40, anchor='start', sm=True)
    return svg(s, 'Снятие жгута, гемостаз, ушивание')


