PROX = '← к туловищу'
DIST = 'к колену →'


def thigh(skin_x=600, sup_x=600, deep_x=600, bone_x=600):
    """Продольный разрез бедра: проксимальный конец слева. *_x — где заканчивается слой после рассечения."""
    bands = [  # (y0, y1, слой)
        (40, 58, 'skin'), (58, 84, 'fat'), (84, 124, 'sup'), (124, 172, 'deep'),
        (248, 296, 'deep'), (296, 336, 'sup'), (336, 362, 'fat'), (362, 380, 'skin')]
    ends = dict(skin=skin_x, fat=skin_x - 6, sup=sup_x, deep=deep_x)
    fills = dict(skin=C['skin'], fat='url(#fatp)', sup='url(#fib)', deep='url(#fibh)')
    s = ''
    for y0, y1, k in bands:
        s += rect(40, y0, ends[k] - 40, y1 - y0, fills[k], stroke='#ffffff', sw=0.6)
    s += rect(40, 182, bone_x - 40, 56, C['bone'], stroke=C['bone_line'], sw=2)
    s += rect(40, 198, bone_x - 40, 24, C['marrow'])
    s += path(f'M40 262 L{deep_x - 4} 262', stroke=C['artery'], sw=5)
    s += path(f'M40 274 L{deep_x - 4} 274', stroke=C['vein'], sw=6)
    s += path(f'M40 150 L{deep_x - 4} 150', stroke=C['nerve'], sw=5)
    s += text(40, 395, PROX, sm=True, color=C['muted']) + text(600, 395, DIST, anchor='end', sm=True, color=C['muted'])
    return s


