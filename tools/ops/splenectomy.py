def s_bed():
    s = scene(spleen=False, short=False, ligaments=False)
    s += path(SPLEEN, fill='none', stroke=C['spleen'], sw=2, extra='stroke-dasharray="6 5"')
    for x, y in ((432, 252), (440, 270), (448, 290)):
        s += knot(x, y, 5)
    s += label(520, 60, 'гемостаз: особенно\nкупол диафрагмы', 470, 110, anchor='start', sm=True)
    s += label(440, 300, 'культи сосудов\nперитонизировать', 470, 350, anchor='start', sm=True)
    s += label(430, 300, 'проверить хвост\nподжелудочной железы', 60, 120, anchor='start', sm=True)
    return svg(s, 'Ложе после удаления')


def s_drain():
    s = torso(show_inguinal=False, navel=(320, 240))
    s += path('M330 120 Q390 180 455 160', stroke=C['skin_line'], sw=3)
    for x in range(345, 455, 18):
        s += suture(f'M{x} {150 + (x - 345) * 0.25 - 8} l2 18', 2)
    s += circle(450, 225, 7, C['tube'], stroke='#b7791f', sw=2)
    s += path('M450 225 Q520 260 600 250', stroke=C['tube'], sw=8)
    s += label(450, 225, 'дренаж через отдельный\nпрокол в левом подреберье', 440, 330, anchor='start')
    s += label(400, 165, 'рана ушита наглухо', 300, 70, anchor='start', sm=True)
    return svg(s, 'Дренирование и закрытие раны')


