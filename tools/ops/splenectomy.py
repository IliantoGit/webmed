def scene(stomach=True, ligaments=True, artery=True, vein=True, short=True, pancreas=True, spleen=True, diaphragm=True):
    s = ''
    if diaphragm:
        s += path('M60 62 Q330 22 620 62', stroke='#c46f62', sw=10, extra='stroke-opacity="0.5"')
        s += text(615, 80, 'диафрагма', anchor='end', sm=True, color=C['muted'])
    if stomach:
        s += path('M60 80 Q200 50 280 120 Q320 200 280 290 Q200 360 80 340 Z', fill=C['stomach'], stroke=C['stomach_line'], sw=2)
        s += text(110, 210, 'желудок')
    if pancreas:
        s += path('M60 340 Q250 300 430 290 Q470 290 470 310 Q440 330 260 350 Q140 370 60 375 Z', fill='#f2d38c', stroke='#c9a24a', sw=1.5)
        s += text(200, 372, 'поджелудочная железа (хвост)', sm=True)
    if ligaments:
        s += path('M282 130 Q360 120 410 125 L455 200 Q400 230 300 260 Z', fill='#f7e3a8', extra='fill-opacity="0.75"', stroke='#d8b964', sw=1)
    if short:
        for y in (140, 175, 210):
            s += path(f'M300 {y + 20} Q360 {y} 430 {y - 5}', stroke=C['artery'], sw=2)
    if artery:
        s += path('M60 320 Q250 285 420 270 Q440 260 455 230', stroke=C['artery'], sw=6)
        for dy in (-40, 0, 40):
            s += path(f'M420 270 Q440 {250 + dy} 462 {235 + dy}', stroke=C['artery'], sw=3)
    if vein:
        s += path('M60 335 Q250 300 425 290 Q448 285 462 262', stroke=C['vein'], sw=7)
    if spleen:
        s += path(SPLEEN, fill=C['spleen'], stroke=C['spleen_line'], sw=2)
        s += text(530, 200, 'селезёнка', color='#fff')
    return s


def s_access():
    s = torso(show_inguinal=False, navel=(320, 240))
    s += cutline('M330 120 Q390 180 455 160', 4)
    s += path('M320 85 L320 230', stroke=C['accent'], sw=2.5, extra='stroke-dasharray="8 6"')
    s += label(400, 168, 'косой разрез параллельно\nлевой рёберной дуге', 440, 260, anchor='start')
    s += label(320, 150, 'или верхняя срединная\nлапаротомия (при травме)', 60, 300, anchor='start', sm=True)
    return svg(s, 'Доступ')


