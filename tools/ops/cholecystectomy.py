def hepatobiliary(gb=True, artery=True, cystic=True, calot=False, peritoneum_cut=False):
    s = path('M40 60 Q330 35 610 65 L610 150 Q470 180 340 152 Q210 185 40 150 Z', fill=C['liver'], stroke=C['liver_line'], sw=2)
    s += text(520, 110, 'печень')
    # двенадцатиперстная кишка
    s += path('M230 360 Q420 330 620 350', stroke=C['bowel_line'], sw=48, extra='stroke-linecap="round"')
    s += path('M230 360 Q420 330 620 350', stroke=C['bowel'], sw=44, extra='stroke-linecap="round"')
    s += text(610, 392, 'двенадцатиперстная кишка', anchor='end', sm=True)
    # воротная вена (позади)
    s += path('M415 340 L405 160', stroke=C['vein'], sw=22, extra='stroke-opacity="0.35" stroke-linecap="round"')
    if calot:
        s += path('M305 178 Q340 205 368 228 L375 150 Q340 155 305 160 Z', fill='#fff3b0', stroke='#e0b400', sw=1.5)
    # протоки: общий печёночный → общий желчный
    s += path('M378 150 L370 228 L382 335', stroke=C['duct'], sw=11, extra='stroke-linecap="round"')
    if cystic:
        s += path('M300 180 Q335 210 370 228', stroke=C['duct'], sw=7)
    if artery:
        s += path('M440 340 Q445 250 430 205 Q400 170 330 150', stroke=C['artery'], sw=5)  # собственная → правая печёночная
        s += path('M392 168 Q350 175 315 188', stroke=C['artery'], sw=3)  # пузырная артерия
    if gb:
        s += path('M300 160 Q330 180 300 200 Q250 290 175 300 Q120 300 130 250 Q150 180 230 158 Z',
                  fill=C['gall'], stroke=C['gall_line'], sw=2)
    if peritoneum_cut:
        s += cutline('M330 245 Q380 200 430 255', 3)
    return s


