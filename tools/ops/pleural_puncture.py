def intercostal(needle=None, anesth=False, fluid=True):
    s = rect(40, 60, 560, 26, C['skin']) + rect(40, 86, 560, 30, 'url(#fatp)') + rect(40, 116, 560, 40, 'url(#fib2)')
    s += f'<ellipse cx="150" cy="185" rx="70" ry="34" fill="{C["bone"]}" stroke="{C["bone_line"]}" stroke-width="2"/>'
    s += f'<ellipse cx="490" cy="185" rx="70" ry="34" fill="{C["bone"]}" stroke="{C["bone_line"]}" stroke-width="2"/>'
    s += rect(220, 156, 200, 60, 'url(#fib)')
    s += circle(200, 214, 7, C['vein']) + circle(214, 222, 6, C['artery']) + circle(226, 228, 5, C['nerve'])
    s += rect(40, 236, 560, 6, C['fascia']) + rect(40, 242, 560, 5, C['peritoneum'])
    if fluid:
        s += rect(40, 247, 560, 70, '#bcdcf5')
        s += text(470, 290, 'выпот', sm=True)
    s += rect(40, 317, 560, 6, C['peritoneum'])
    s += rect(40, 323, 560, 60, '#f2c7c9')
    s += text(470, 360, 'лёгкое', sm=True)
    s += text(150, 190, 'ребро\n(верхнее)', anchor='middle', sm=True)
    s += text(490, 190, 'ребро\n(нижнее)', anchor='middle', sm=True)
    s += label(214, 222, 'межрёберные вена, артерия,\nнерв — у НИЖНЕГО края ребра', 40, 300, anchor='start', sm=True)
    if anesth:
        for x, y in ((420, 100), (420, 140), (420, 200), (425, 232)):
            s += f'<ellipse cx="{x}" cy="{y}" rx="18" ry="9" fill="#a5f3fc" fill-opacity="0.6"/>'
    if needle:
        s += needle
    return s


