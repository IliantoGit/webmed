def back():
    s = path('M160 40 Q150 200 170 380 L470 380 Q490 200 480 40 Z', fill=C['skin'], stroke=C['skin_line'], sw=2)
    s += path('M320 45 L320 375', stroke=C['skin_line'], sw=2, extra='stroke-dasharray="3 5"')
    for i in range(9):
        y = 70 + i * 34
        s += path(f'M330 {y} Q420 {y + 10} 470 {y + 34}', stroke=C['bone_line'], sw=2, extra='stroke-opacity="0.7"')
        s += path(f'M310 {y} Q220 {y + 10} 170 {y + 34}', stroke=C['bone_line'], sw=2, extra='stroke-opacity="0.7"')
    s += path('M360 70 L430 80 L410 190 Z', fill='#e9d8c4', stroke=C['bone_line'], sw=1.5, extra='fill-opacity="0.7"')
