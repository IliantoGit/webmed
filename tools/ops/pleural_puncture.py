def s_errors():
    s = rect(40, 60, 560, 40, C['skin'])
    s += path('M40 100 L600 100 L600 330 Q330 360 40 330 Z', fill='#f2c7c9')
    s += path('M40 230 L600 230 L600 330 Q330 360 40 330 Z', fill='#bcdcf5')
    s += path('M40 330 Q330 360 600 330 L600 400 L40 400 Z', fill=C['liver'])
    s += text(560, 220, 'лёгкое', anchor='end', sm=True) + text(560, 300, 'выпот', anchor='end', sm=True)
    s += text(560, 385, 'диафрагма / печень', anchor='end', sm=True, color='#fff')
    for x, y2, ok, lab in ((100, 280, True, '✓ в выпот'), (240, 200, False, '✗ в лёгкое\n(над выпотом)'),
                           (380, 380, False, '✗ через синус\nв брюшную полость'), (520, 225, False, '✗ над выпотом /\nв спайку')):
        col = C['accent'] if ok else C['cut']
        s += path(f'M{x} 78 L{x} {y2}', stroke=col, sw=3)
        s += text(x, 48 if x != 380 else 48, lab, anchor='middle', sm=True, color=col)
    s = s.replace('<rect x="40" y="60"', '<rect x="40" y="80"', 1)
    return svg(s)


