def field(apo_open=True, cord=True, muscles=True, nerve=True, sac=None, cord_lift=False, fascia_cut=False):
    """Паховая область сверху: паховая связка внизу горизонтально, латеральное — слева."""
    s = f'<ellipse cx="320" cy="215" rx="290" ry="160" fill="{C["skin"]}" stroke="{C["skin_line"]}" stroke-width="2"/>'
    s += '<ellipse cx="320" cy="215" rx="270" ry="140" fill="url(#fatp)"/>'
    s += '<ellipse cx="320" cy="215" rx="250" ry="122" fill="url(#apo)"/>'
    if apo_open:
        s += path('M80 210 Q320 150 560 220 L560 300 Q320 330 80 300 Z', fill=C['fascia'])  # дно канала: поперечная фасция
        if fascia_cut:
            s += path('M190 255 Q350 250 520 268 L520 292 Q350 288 190 285 Z', fill=C['peritoneum'], stroke='#6aa889', sw=1.5)
        if muscles:
            s += path('M70 150 Q320 110 570 160 L570 205 Q320 175 70 200 Z', fill='url(#fib)', stroke=C['muscle_line'], sw=1.2)
        # паховая связка (желоб)
        s += path('M70 305 Q320 330 575 300', stroke='#c9d5e2', sw=18, extra='stroke-linecap="round"')
        s += path('M70 305 Q320 330 575 300', stroke=C['apo_line'], sw=1.5)
        # нижние надчревные сосуды у глубокого кольца
        s += path('M215 330 Q222 260 235 215', stroke=C['artery'], sw=3) + path('M224 330 Q231 260 244 215', stroke=C['vein'], sw=3)
        # края апоневроза на зажимах
        s += path('M80 205 Q320 140 560 215', stroke=C['apo_line'], sw=3)
        s += path('M80 300 Q320 335 560 300', stroke=C['apo_line'], sw=3)
    if cord:
        y0 = 230 if not cord_lift else 200
        cp = f'M150 {y0} Q330 {y0 + 20} 560 {y0 + 40}'
        s += path(cp, stroke='#d9a08f', sw=30, extra='stroke-linecap="round"')
        s += path(cp, stroke='#efc2b3', sw=26, extra='stroke-linecap="round"')
        s += path(f'M150 {y0 - 5} Q330 {y0 + 15} 560 {y0 + 35}', stroke=C['artery'], sw=1.5)
        s += path(f'M150 {y0 + 4} Q330 {y0 + 24} 560 {y0 + 44}', stroke=C['vein'], sw=1.5)
        s += path(f'M150 {y0 + 9} Q330 {y0 + 29} 560 {y0 + 49}', stroke='#f8f1e8', sw=3)
        if nerve:
            s += path(f'M170 {y0 - 14} Q330 {y0 + 4} 560 {y0 + 24}', stroke=C['nerve'], sw=3)
    if sac:
        s += sac
    return s


