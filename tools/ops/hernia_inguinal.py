def s_bassini():
    s = field(cord=False)
    xs = [520, 470, 420, 370, 320, 270, 225]
    for x in xs:
        y1 = 190 - (x - 320) * 0.06
        y2 = 312 + (x - 320) * 0.02 + (6 if xs.index(x) % 2 else 0)
        s += suture(f'M{x} {y1} Q{x + 18} {(y1 + y2) / 2} {x} {y2}', 2.2) + knot(x, y1, 3)
    s += f'<ellipse cx="195" cy="232" rx="16" ry="12" fill="#efc2b3" stroke="#d9a08f" stroke-width="2"/>'
    s += label(470, 200, '6–8 швов: пластина →\nпаховая связка', 450, 60, anchor='start')
    s += label(520, 315, 'первый шов — через\nнадкостницу лобкового\nбугорка', 470, 360, anchor='start', sm=True)
    s += label(195, 232, 'новое глубокое кольцо —\nпропускает кончик мизинца', 40, 90, anchor='start', sm=True)
    s += text(40, 365, 'выколы в связке — то ближе,\nто дальше от края', sm=True, color=C['accent'])
    return svg(s, 'Пластика по Бассини')


