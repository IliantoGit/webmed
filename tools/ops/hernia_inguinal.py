def sac_shape(opened=False, ligated=False, cut=False):
    if cut:
        return (path('M150 205 Q175 225 205 210 L200 250 Q175 262 150 245 Z', fill='#f3f6fa', stroke=C['apo_line'], sw=2)
                + ligature(150, 228, 206, 228))
    s = path('M150 205 Q300 150 430 200 Q470 260 420 300 Q300 320 150 250 Z', fill='#f3f6fa', stroke=C['apo_line'], sw=2.5)
    if opened:
        s += path('M200 228 Q320 200 410 250', stroke=C['cut'], sw=2.5)
        s += path('M230 240 Q320 225 380 255 Q330 275 250 262 Z', fill=C['bowel'], stroke=C['bowel_line'], sw=2)
    if ligated:
        s += ligature(165, 205, 168, 252) + suture('M166 205 Q140 228 167 252', 2)
    return s


