def neck(isthmus_shift=0, muscles=False, skin=True, rings_only=False):
    s = ''
    if skin:
        s += path('M180 20 Q170 200 140 390 L500 390 Q470 200 460 20 Z', fill=C['skin'], stroke=C['skin_line'], sw=2)
    if muscles:
        s += path('M240 60 L285 60 L280 380 L230 380 Z', fill='url(#fibh)', stroke=C['muscle_line'], sw=1, extra='opacity="0.85"')
        s += path('M355 60 L400 60 L410 380 L360 380 Z', fill='url(#fibh)', stroke=C['muscle_line'], sw=1, extra='opacity="0.85"')
    # щитовидный хрящ
    s += path('M270 50 L370 50 L345 135 L320 145 L295 135 Z', fill=C['cart'], stroke=C['cart_line'], sw=2)
    # перстневидный хрящ
    s += rect(285, 160, 70, 16, C['cart'], stroke=C['cart_line'], rx=6)
    # коническая связка
    s += rect(298, 145, 44, 14, '#dfe8f0', stroke=C['cart_line'], sw=0.8)
    # кольца трахеи
    for i in range(10):
        y = 186 + i * 20
        s += rect(292, y, 56, 12, C['cart'], stroke=C['cart_line'], rx=5)
    if not rings_only:
        # щитовидная железа: доли и перешеек
        dy = isthmus_shift
        s += path(f'M250 170 Q230 230 260 280 Q285 290 295 250 L295 {205 + dy} L345 {205 + dy} L345 250 Q355 290 380 280 Q410 230 390 170 Q370 160 350 185 L350 {200 + dy} L290 {200 + dy} L290 185 Q270 160 250 170 Z',
                  fill='#c9564d', stroke='#8f2f28', sw=1.5, extra='fill-opacity="0.85"')
        s += rect(290, 200 + dy, 60, 40, '#c9564d', stroke='#8f2f28', sw=1.5)
    return s


